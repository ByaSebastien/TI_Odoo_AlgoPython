"""Premier script : afficher du texte et des calculs avec print."""

# Un commentaire commence par # : Python l'ignore entièrement.

print("Bonjour !")
print("Python exécute les instructions de haut en bas.")

# Texte entre guillemets, nombres sans guillemets.
print("2 + 3")
print(2 + 3)

# Plusieurs éléments, séparés par des virgules : print ajoute un espace entre eux.
print("Deux plus trois font", 2 + 3)
print("Prix de 3 livres à 12,50 € :", 3 * 12.50, "€")

# Les guillemets simples fonctionnent aussi : pratique si le texte contient un ".
print('Il a dit "bonjour".')
print("C'est parti !")

# Un print vide affiche une ligne vide.
print()
print("Fin du programme.")
